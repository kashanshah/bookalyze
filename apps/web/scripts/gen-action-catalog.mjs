#!/usr/bin/env node
/**
 * Writes src/server/api/action-catalog.generated.ts: every company-scoped server action (a
 * `"use server"` file under app/o/[slug] whose exported function takes the company's slug first),
 * so the public API and MCP server can call anything the app's screens can, with the same
 * validation, permissions and audit as the browser. New actions appear here on the next build.
 *
 * Left out: company settings (members, billing, modules, general), help, and actions taking form
 * data. Run with `--check` to fail when the committed file is out of date (CI's typecheck does).
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "src/app/o/[slug]");
const out = join(root, "src/server/api/action-catalog.generated.ts");

/** Areas never reachable through an API key: who's in the company, what it pays, support. */
const EXCLUDED = [/^settings\//, /^help\//];
const MODULE_OF = {
  accounting: "accounting",
  banking: "banking",
  commerce: "commerce",
  inventory: "inventory",
  reviews: "reviews",
  company: "entity",
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

/** The JSDoc right above `index`, as plain text. */
function docBefore(source, index) {
  const before = source.slice(0, index).trimEnd();
  if (!before.endsWith("*/")) return "";
  const start = before.lastIndexOf("/**");
  if (start < 0) return "";
  return before
    .slice(start + 3, -2)
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, "").trim())
    .filter(Boolean)
    .join(" ");
}

/** The text between the parentheses that start at `open`. */
function paramsAt(source, open) {
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    const c = source[i];
    if (c === "(") depth++;
    else if (c === ")") {
      depth--;
      if (depth === 0) return source.slice(open + 1, i);
    }
  }
  return "";
}

/** Splits "a: string, b: { x: 1, y: 2 }" at top-level commas. */
function splitParams(text) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const c of text) {
    if ("({[<".includes(c)) depth++;
    if (")}]>".includes(c)) depth--;
    if (c === "," && depth === 0) {
      parts.push(current);
      current = "";
    } else current += c;
  }
  parts.push(current);
  return parts.map((p) => p.replace(/\s+/g, " ").trim()).filter(Boolean);
}

const entries = [];
const imports = [];
for (const file of walk(appDir)
  .filter((f) => /\.tsx?$/.test(f))
  .sort()) {
  const source = readFileSync(file, "utf8");
  if (!/^\s*["']use server["']/.test(source)) continue;
  const rel = relative(appDir, file).replaceAll("\\", "/");
  if (EXCLUDED.some((re) => re.test(rel))) continue;
  const area = rel.split("/")[0];
  const module = MODULE_OF[area];
  if (!module) continue;
  const alias = `m${imports.length}`;
  const found = [];
  for (const match of source.matchAll(/export async function (\w+)\s*\(/g)) {
    const params = splitParams(paramsAt(source, match.index + match[0].length - 1));
    if (!params[0]?.startsWith("slug")) continue;
    if (params.some((p) => /FormData|^_prev/.test(p))) continue;
    found.push({
      name: match[1],
      params: params.slice(1),
      doc: docBefore(source, match.index),
    });
  }
  if (!found.length) continue;
  const importPath = `@/app/o/[slug]/${rel.replace(/\.tsx?$/, "")}`;
  imports.push(`import * as ${alias} from "${importPath}";`);
  for (const f of found) {
    entries.push(
      `  {\n    name: ${JSON.stringify(f.name)},\n    area: ${JSON.stringify(rel.replace(/\/?[^/]*$/, "") || area)},\n    module: ${JSON.stringify(module)},\n    params: ${JSON.stringify(f.params)},\n    doc: ${JSON.stringify(f.doc)},\n    fn: ${alias}.${f.name} as unknown as ActionFn,\n  },`,
    );
  }
}

const text = `// Generated by scripts/gen-action-catalog.mjs. Don't edit: run \`pnpm --filter @bookalyze/web gen:actions\`.
import "server-only";
import type { ModuleKey } from "@bookalyze/core";
${imports.join("\n")}

export type ActionFn = (slug: string, ...args: unknown[]) => Promise<unknown>;

export type CatalogAction = {
  name: string;
  /** Where it lives in the app, e.g. "accounting/transactions". */
  area: string;
  module: ModuleKey;
  /** Its parameters after the company's slug, as written in the code. */
  params: string[];
  doc: string;
  fn: ActionFn;
};

export const ACTION_CATALOG: CatalogAction[] = [
${entries.join("\n")}
];
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== text) {
    console.error(
      "src/server/api/action-catalog.generated.ts is out of date. Run: pnpm --filter @bookalyze/web gen:actions",
    );
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.info(`Wrote ${entries.length} actions to ${relative(root, out)}`);
}
